// The real Milky Way: a hand-picked catalogue. Positions are J2000 RA/Dec (or galactic l/b)
// and distances from the Sun in light-years, from standard references (Wikipedia/SIMBAD values,
// rounded). Where a distance is uncertain, the common value is used and the summary says so.
import { dms, hms, type ArmFit } from './geo.ts';

export type Pos = { ra: number; dec: number; d: number } | { l: number; b: number; d: number };
const eq = (
  h: number,
  m: number,
  s: number,
  dd: number,
  dm: number,
  ds: number,
  d: number,
): Pos => ({
  ra: hms(h, m, s),
  dec: dms(dd, dm, ds),
  d,
});
const gal = (l: number, b: number, d: number): Pos => ({ l, b, d });

export interface Star {
  key: string;
  name: string;
  tempK: number;
  spectral: string;
  massSun?: number;
  /** System-frame position (AU, or schematic for compact systems). */
  at?: [number, number];
  scale?: number;
  summary?: string;
  wiki?: string;
}
export interface Planet {
  key: string;
  name: string;
  orbitAu: number;
  /** Drawn distance from its star in the system frame, if not the real one. */
  drawAt?: number;
  /** Key of the star it orbits, when the system has several. */
  around?: string;
  radiusEarth?: number;
  massEarth?: number;
  preset: string;
  palette?: string[];
  scale?: number;
  summary?: string;
  wiki?: string;
  extra?: Record<string, unknown>;
}
export interface Belt {
  key: string;
  name: string;
  at: number;
  scale: number;
  summary?: string;
  around?: string;
}
export interface StarSystem {
  key: string;
  name: string;
  pos: Pos;
  constellation: string;
  summary: string;
  description?: string;
  wiki: string;
  priority?: number;
  schematic?: boolean;
  stars: Star[];
  planets?: Planet[];
  belts?: Belt[];
  blackHoles?: {
    key: string;
    name: string;
    massSun: number;
    at: [number, number];
    summary?: string;
  }[];
  discovered?: string;
  arm?: string;
}

