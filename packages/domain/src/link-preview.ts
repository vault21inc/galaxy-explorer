/**
 * Link previews (M8-T9): the card a chat app or social site shows for a shared link, with a
 * title, a line of text and an image. The programs that draw those cards fetch the page and
 * read its `<meta>` tags without running scripts, so the app's own page, the same
 * `index.html` for every address, would give them nothing. Those programs are sent to the
 * API instead, which writes a small page of tags for that address. People get the app.
 *
 * Three things send them there, from these lists, so they can't drift apart:
 * - Caddy, on the site: `ops/caddy/link-previews.caddy`, generated by `pnpm headers:caddy`;
 * - `vite preview`, so the e2e tests see what a chat app would (apps/web/vite.config.js);
 * - nothing in development, where `pnpm dev` serves only the app.
 *
 * Kept apart from the rest of the domain package (its own `@ge/domain/link-preview` entry),
 * like the security headers, so the Vite config can load it without the rest.
 */

/** The API's route that writes a preview page. It takes the page's `path` and query. */
export const LINK_PREVIEW_ROUTE = '/api/v1/link-preview';

/**
 * The programs that fetch link previews and search results, by a word in their User-Agent,
 * matched without regard to case. Named one by one rather than any "bot", so that no person's
 * browser is mistaken for one: a phone called the CUBOT X30 puts "CUBOT" in its User-Agent.
 * Apple's Messages fetches as `facebookexternalhit` and `Twitterbot`, and Signal as `WhatsApp`.
 */
export const LINK_PREVIEW_AGENTS = [
  // Chat apps and social sites.
  'slackbot',
  'discordbot',
  'twitterbot',
  'facebookexternalhit',
  'facebot',
  'linkedinbot',
  'telegrambot',
  'whatsapp',
  'skypeuripreview',
  'redditbot',
  'mastodon',
  // Bluesky's card fetcher.
  'cardyb',
  'pinterestbot',
  'vkshare',
  // Link-expanding services that other apps use.
  'embedly',
  'iframely',
  // Search engines, which then index the page's title and text.
  'googlebot',
  'google-inspectiontool',
  'bingbot',
  'applebot',
  'duckduckbot',
  'yandexbot',
] as const;

/** The agents as one regular expression's source, for `new RegExp(…, 'i')` and Caddy's `(?i)`. */
export const LINK_PREVIEW_AGENT_PATTERN = `(?:${LINK_PREVIEW_AGENTS.map((agent) =>
  agent.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'),
).join('|')})`;

/**
 * The addresses that have previews: a universe, one of its maps, and an object's view, with
 * an optional trailing slash. Their parts are slugs and ids, so a matched path can go into a
 * query string as it is. (`…?select=<id>`, the selected object, rides in the query.) No
 * `{n}` counts: in a Caddyfile, braces are placeholders. The API checks the id itself.
 */
export const LINK_PREVIEW_PATH_PATTERN =
  '^/u/[a-z0-9]+(?:-[a-z0-9]+)*(?:/[a-z0-9]+(?:-[a-z0-9]+)*(?:/view/[0-9a-f-]+)?)?/?$';

const AGENT = new RegExp(LINK_PREVIEW_AGENT_PATTERN, 'i');
const PATH = new RegExp(LINK_PREVIEW_PATH_PATTERN);

/** Whether a request for `path` from `userAgent` should get the preview page. */
export function wantsLinkPreview(path: string, userAgent: string | undefined): boolean {
  return userAgent !== undefined && AGENT.test(userAgent) && PATH.test(path);
}

/** The site's name, last in every page title and as `og:site_name`. */
export const SITE_NAME = 'Galaxy Explorer';

/**
 * A page's title, from the most particular part to the most general, then the site:
 * "Gudrun · M41 · Eisenhorn · Galaxy Explorer". The browser tab (the web app) and the preview
 * card (the API) use the same one. Empty parts are left out.
 */
export function pageTitle(parts: readonly (string | null | undefined)[]): string {
  return [...parts.filter((part): part is string => !!part?.trim()), SITE_NAME].join(' · ');
}
